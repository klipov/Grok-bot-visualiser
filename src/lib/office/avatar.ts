export function suggestAvatar(name: string): AvatarStyle {
  const words =
    name
      .normalize("NFD")
      .replace(/\p{M}/gu, "")
      .toLowerCase()
      .match(/\p{L}+/gu) ?? [];
  const feminine = words.some((word) => feminineNames.has(word));
  const masculine = words.some((word) => masculineNames.has(word));
  if (feminine === masculine) return "neutral";
  return feminine ? "feminine" : "masculine";
}

export function avatarSpriteUrl(style: AvatarStyle): string {
  return `/office/avatar-${style}.png`;
}
